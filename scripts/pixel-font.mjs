export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const TRACKING = 1; // пустой столбец между буквами

const GLYPHS = Object.fromEntries(
  Object.entries(RAW).map(([char, rows]) => [char, rows.split("/").map((row) => row.padEnd(GLYPH_W, "0"))]),
);

for (const [char, rows] of Object.entries(GLYPHS)) {
  if (rows.length !== GLYPH_H) throw new Error(`Глиф «${char}»: ${rows.length} строк вместо ${GLYPH_H}`);
  for (const row of rows) {
    if (row.length !== GLYPH_W) throw new Error(`Глиф «${char}»: строка «${row}» не ${GLYPH_W} символов`);
    if (/[^01]/.test(row)) throw new Error(`Глиф «${char}»: в строке «${row}» есть посторонние символы`);
  }
}

export function measure(text, scale) {
  return text.length * (GLYPH_W + TRACKING) * scale - TRACKING * scale;
}

// Возвращает path с пикселями текста; начало координат — левый верхний угол строки.
export function textPath(text, x, y, scale, anchor = "start") {
  const width = measure(text, scale);
  let cursorX = anchor === "end" ? x - width : anchor === "middle" ? x - width / 2 : x;
  const parts = [];

  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char] || GLYPHS["?"];
    for (let row = 0; row < GLYPH_H; row++) {
      let col = 0;
      while (col < GLYPH_W) {
        if (glyph[row][col] !== "1") {
          col++;
          continue;
        }
        let run = 1;
        while (col + run < GLYPH_W && glyph[row][col + run] === "1") run++;
        parts.push(
          `M${cursorX + col * scale} ${y + row * scale}h${run * scale}v${scale}h${-run * scale}z`,
        );
        col += run;
      }
    }
    cursorX += (GLYPH_W + TRACKING) * scale;
  }

  return { d: parts.join(""), width };
}
